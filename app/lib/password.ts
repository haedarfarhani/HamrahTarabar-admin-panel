/**
 * سیاست مشترک رمز عبور برای فرم‌های ثبت‌نام، بازیابی رمز و تغییر رمز عبور.
 *
 * قاعده (هم‌تراز با الگوی بک‌اند در RegisterDto و ChangePasswordDto):
 * حداقل ۸ کاراکتر و شامل حرف کوچک، حرف بزرگ، عدد و یک کاراکتر خاص از
 * مجموعه‌ی (@$!%*?&). سایر کاراکترها و فاصله پذیرفته نمی‌شوند.
 *
 * این تنها منبع حقیقت است؛ اگر سیاست بک‌اند تغییر کرد فقط همین فایل
 * به‌روزرسانی می‌شود و هر سه فرم با هم هم‌تراز می‌مانند.
 */
export const PASSWORD_REGEX = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]{8,}$/;

